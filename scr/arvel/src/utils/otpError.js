// Текст ошибки для экранов ввода SMS-кода. Бэкенд на неверный код отвечает
// detail по-английски («invalid verification code»), и он показывался как есть.
// Ответ сервера «код не принят» переводим сами; сетевые ошибки клиент уже
// формулирует по-русски (см. api/client.js) — их оставляем.
export function otpErrorMessage(e) {
  const status = e?.status;
  if (status === 400 || status === 401 || status === 422) return 'Неверный код. Попробуйте ещё раз.';
  if (status === 429) return 'Слишком много попыток. Подождите немного и попробуйте снова.';
  return e?.message || 'Неверный код. Попробуйте ещё раз.';
}
